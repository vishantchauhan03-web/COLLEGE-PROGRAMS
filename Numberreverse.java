class Numberreverse{
    public static void main(String arr[]){
        for (int i =1;i<=10;i++){
            for(int j =1;j<=i;j++){
                System.out.print(j);
            } System.out.println();
       }
       for(int k=9;k>=1;k--){
        for(int l=1;l<=k;l++){
            System.out.print(l);
        }System.out.println();
       }
    }
}